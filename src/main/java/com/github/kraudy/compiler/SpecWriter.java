package com.github.kraudy.compiler;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.io.UncheckedIOException;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.function.Function;

import com.fasterxml.jackson.core.JsonProcessingException;
import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.fasterxml.jackson.databind.node.ObjectNode;
import com.fasterxml.jackson.dataformat.yaml.YAMLFactory;
import com.fasterxml.jackson.dataformat.yaml.YAMLGenerator;
import com.github.kraudy.compiler.CompilationPattern.ParamCmd;

/**
 * Writes a readable YAML build spec from a {@link BuildSpec}.
 * Emits global hooks, per-target hooks, and resolved {@code params}
 * (SRCSTMF, MODULE, PGM, defaults, inspection, ...). Target map order is preserved (topo-sorted).
 */
public final class SpecWriter {

  private SpecWriter() {}

  /* The spec's top-level settings, written as declared (mc-base.yaml merged by --scan): name -> its value. Not here:
     defaults (already in each target's params), curlib / libl (already the CHGLIBL / CHGCURLIB before hook) */
  static final Map<String, Function<BuildSpec, Object>> SETTINGS = new LinkedHashMap<String, Function<BuildSpec, Object>>();
  static {
    SETTINGS.put("protectedLibs", s -> s.protectedLibs);
    SETTINGS.put("uploadFolders", s -> s.uploadFolders);
    SETTINGS.put("uploadSources", s -> s.uploadSources);
    SETTINGS.put("hookTimeout", s -> s.hookTimeout);
    SETTINGS.put("inquiryReply", s -> s.inquiryReply);
    SETTINGS.put("connections", s -> s.connections);
  }

  private static final ObjectMapper YAML = new ObjectMapper(new YAMLFactory()
      .disable(YAMLGenerator.Feature.WRITE_DOC_START_MARKER)
      .enable(YAMLGenerator.Feature.MINIMIZE_QUOTES));
  private static final ObjectMapper JSON = new ObjectMapper();  // a JSON string or list is a YAML flow scalar / sequence

  public static String toYaml(BuildSpec spec) {
    return toYaml(spec, null);
  }

  public static String toYaml(BuildSpec spec, String scanRootComment) {
    StringBuilder sb = new StringBuilder();
    sb.append("# Generated by MasterCompiler --scan\n");
    if (scanRootComment != null && !scanRootComment.isEmpty()) {
      sb.append("# Root: ").append(scanRootComment).append("\n");
    }
    if (spec.getBaseDirectory() != null) {
      sb.append("# Base directory: ").append(spec.getBaseDirectory()).append("\n");
    }
    sb.append("\n");

    writeSettings(sb, spec);
    writeHookSection(sb, "before", spec.before, "");
    writeHookSection(sb, "after", spec.after, "");
    writeHookSection(sb, "success", spec.success, "");
    writeHookSection(sb, "failure", spec.failure, "");

    sb.append("targets:\n");

    for (Map.Entry<TargetKey, BuildSpec.TargetSpec> entry : spec.targets.entrySet()) {
      TargetKey key = entry.getKey();
      BuildSpec.TargetSpec targetSpec = entry.getValue();

      String paste = CommandStringParser.toPasteableCommand(
          key, spec.defaults, targetSpec.params);
      if (paste != null && !paste.isEmpty()) {
        sb.append("  # ").append(paste).append("\n");
      }

      sb.append("  \"").append(escapeYamlDouble(key.asString())).append("\":\n");
      if (targetSpec.recreate != null) sb.append("    recreate: ").append(targetSpec.recreate).append("\n");

      boolean hasParams = targetSpec.params != null && !targetSpec.params.isEmpty();
      boolean hasBefore = targetSpec.before != null && !targetSpec.before.isEmpty();
      boolean hasAfter = targetSpec.after != null && !targetSpec.after.isEmpty();
      boolean hasSuccess = targetSpec.success != null && !targetSpec.success.isEmpty();
      boolean hasFailure = targetSpec.failure != null && !targetSpec.failure.isEmpty();

      if (!hasParams && !hasBefore && !hasAfter && !hasSuccess && !hasFailure) {
        sb.append("    params: {}\n");
        sb.append("\n");
        continue;
      }

      writeHookSection(sb, "before", targetSpec.before, "    ");
      writeHookSection(sb, "after", targetSpec.after, "    ");
      writeHookSection(sb, "success", targetSpec.success, "    ");
      writeHookSection(sb, "failure", targetSpec.failure, "    ");

      if (hasParams) {
        sb.append("    params:\n");
        List<ParamCmd> ordered = orderedParams(key, targetSpec.params);
        for (ParamCmd param : ordered) {
          String value = targetSpec.params.get(param);
          if (value == null) continue;
          writeParam(sb, param, value);
        }
      } else {
        sb.append("    params: {}\n");
      }
      sb.append("\n");
    }

    return sb.toString();
  }

  /**
   * Emit hooks as a YAML list (supports repeated commands like multiple ADDMSGD).
   * Indent is the YAML indent for the section key ("" global, "    " under target).
   */
  private static void writeHookSection(
      StringBuilder sb, String section, List<CommandObject> hooks, String indent) {
    if (hooks == null || hooks.isEmpty()) return;

    sb.append(indent).append(section).append(":\n");
    String itemIndent = indent + "  ";
    String cmdIndent = indent + "    ";
    String paramIndent = indent + "      ";

    for (CommandObject cmd : hooks) {
      if (cmd == null) continue;
      if (cmd.isRaw()) {
        /* as written in the spec: CommandObject.raw doubled its quotes for QCMDEXC */
        sb.append(itemIndent).append("- Cmd: ").append(json(cmd.getCommandString().replace("''", "'"))).append("\n");
        writeHookOptions(sb, cmd, cmdIndent);
        continue;
      }
      sb.append(itemIndent).append("- ").append(cmd.getSystemCommandName()).append(":\n");
      List<ParamCmd> pattern = CompilationPattern.getCommandPattern(cmd.getSystemCommand());
      boolean wroteAny = false;
      for (ParamCmd param : pattern) {
        if (!cmd.containsKey(param)) continue;
        String value = stripIbmQuotes(cmd.get(param));
        if (value == null || value.isEmpty()) continue;

        if ((param == ParamCmd.OBJ || param == ParamCmd.MODULE) && value.contains(" ")) {
          sb.append(paramIndent).append(param.name()).append(":\n");
          for (String part : value.trim().split("\\s+")) {
            if (part.isEmpty()) continue;
            String name = withoutLibl(part);
            sb.append(paramIndent).append("  - ").append(scalar(name)).append("\n");
          }
          wroteAny = true;
          continue;
        }

        sb.append(paramIndent).append(param.name()).append(": ");
        if (needsQuoting(value)) {
          sb.append("\"").append(escapeYamlDouble(value)).append("\"");
        } else {
          sb.append(value);
        }
        sb.append("\n");
        wroteAny = true;
      }
      if (!wroteAny) {
        sb.append(paramIndent).append("{}\n");
      }
      writeHookOptions(sb, cmd, cmdIndent);
    }
    if (indent.isEmpty()) {
      sb.append("\n");
    }
  }

  public static void writeToFile(BuildSpec spec, String outputPath) throws IOException {
    writeToFile(spec, outputPath, null);
  }

  public static void writeToFile(BuildSpec spec, String outputPath, String scanRootComment)
      throws IOException {
    Path path = Paths.get(outputPath);
    Path parent = path.getParent();
    if (parent != null) {
      Files.createDirectories(parent);
    }
    Files.write(path, toYaml(spec, scanRootComment).getBytes(StandardCharsets.UTF_8));
    Path clPath = clPathFor(path);
    Files.write(clPath, CompileScriptWriter.toCl(spec).getBytes(StandardCharsets.UTF_8));
  }

  static Path clPathFor(Path yamlPath) {
    String name = yamlPath.getFileName().toString();
    int dot = name.lastIndexOf('.');
    String stem = dot > 0 ? name.substring(0, dot) : name;
    Path parent = yamlPath.getParent();
    return parent == null ? Paths.get(stem + ".cl") : parent.resolve(stem + ".cl");
  }

  private static List<ParamCmd> orderedParams(TargetKey key, Map<ParamCmd, String> params) {
    List<ParamCmd> ordered = new ArrayList<>();
    List<ParamCmd> pattern = CompilationPattern.getCommandPattern(key.getCompilationCommand());
    for (ParamCmd p : pattern) {
      if (params.containsKey(p)) ordered.add(p);
    }
    for (ParamCmd p : params.keySet()) {
      if (!ordered.contains(p)) ordered.add(p);
    }
    return ordered;
  }

  private static void writeParam(StringBuilder sb, ParamCmd param, String value) {
    value = stripIbmQuotes(value);
    if (param == ParamCmd.MODULE) {
      String[] modules = value.trim().split("\\s+");
      if (modules.length > 1 || (modules.length == 1 && !modules[0].isEmpty())) {
        sb.append("      ").append(param.name()).append(":\n");
        for (String mod : modules) {
          if (mod.isEmpty()) continue;
          String name = withoutLibl(mod);
          sb.append("        - ").append(scalar(name)).append("\n");
        }
        return;
      }
    }

    sb.append("      ").append(param.name()).append(": ");
    if (needsQuoting(value)) {
      sb.append("\"").append(escapeYamlDouble(value)).append("\"");
    } else {
      sb.append(value);
    }
    sb.append("\n");
  }

  /* The settings MC knows, as a YAML block; null, empty lists and empty maps left out */
  private static void writeSettings(StringBuilder sb, BuildSpec spec) {
    ObjectNode settings = YAML.createObjectNode();
    for (Map.Entry<String, Function<BuildSpec, Object>> setting : SETTINGS.entrySet()) {
      Object value = setting.getValue().apply(spec);
      if (value == null) continue;
      JsonNode node = YAML.valueToTree(value);
      if (node == null || node.isNull() || (node.isContainerNode() && node.size() == 0)) continue;
      settings.set(setting.getKey(), node);
    }
    if (settings.size() == 0) return;
    try {
      sb.append(YAML.writeValueAsString(settings)).append("\n");
    } catch (JsonProcessingException e) {
      throw new UncheckedIOException(e);
    }
  }

  /* ignore and timeout: keys of the hook's own list element, next to its command */
  private static void writeHookOptions(StringBuilder sb, CommandObject cmd, String indent) {
    if (!cmd.getIgnore().isEmpty()) sb.append(indent).append("ignore: ").append(json(cmd.getIgnore())).append("\n");
    if (cmd.getTimeoutSeconds() > 0) sb.append(indent).append("timeout: ").append(cmd.getTimeoutSeconds()).append("\n");
  }

  private static String json(Object value) {
    try {
      return JSON.writeValueAsString(value);
    } catch (JsonProcessingException e) {
      throw new UncheckedIOException(e);
    }
  }

  /* A plain YAML scalar, double-quoted when it would read as something else (*CURLIB/X: an alias) */
  private static String scalar(String value) {
    return needsQuoting(value) ? "\"" + escapeYamlDouble(value) + "\"" : value;
  }

  /* *LIBL/NAME is what NAME means: the library is written only when the spec names one */
  private static String withoutLibl(String name) {
    return name.replaceFirst("(?i)^\\*LIBL/", "");
  }

  /** Peel validateParamValue IBM i quotes so YAML stays logical (re-applied on load). */
  private static String stripIbmQuotes(String value) {
    if (value == null) return null;
    String s = value.trim();
    while (s.startsWith("''") && s.endsWith("''") && s.length() >= 4) {
      s = s.substring(2, s.length() - 2).trim();
    }
    return s;
  }

  private static boolean needsQuoting(String value) {
    if (value.isEmpty()) return true;
    if (value.indexOf(':') >= 0 || value.indexOf('#') >= 0 || value.indexOf('\'') >= 0) return true;
    if (value.indexOf('"') >= 0 || value.indexOf(' ') >= 0) return true;
    if (value.indexOf('*') >= 0 || value.indexOf('/') >= 0) return true;
    return false;
  }

  private static String escapeYamlDouble(String s) {
    return s.replace("\\", "\\\\").replace("\"", "\\\"");
  }
}
